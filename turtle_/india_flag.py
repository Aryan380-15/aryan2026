from turtle import *

t=Turtle()
t.speed(6)
t.penup()
t.fd(-200)
t.left(90)
t.fd(250)
t.pendown()
t.fd(-500)
t.right(90)
t.fd(8)
t.left(90)
t.fd(500)
t.left(90)
t.fd(8)
t.penup()
t.fd(-8)
t.pendown()
t.fillcolor('orange')
t.begin_fill()
t.fd(-250)
t.left(90)
t.fd(60)
t.right(90)
t.fd(250)
t.right(90)
t.fd(60)
t.end_fill()

t.left(180)
t.penup()
t.fd(120)
t.fillcolor('green')
t.begin_fill()
t.pendown()
t.fd(60)

t.left(90)
t.fd(250)
t.left(90)
t.fd(120)
t.penup()
t.fd(-60)
t.pendown()
t.left(90)
t.fd(250)
t.end_fill()
t.penup()
t.fd(-150)

t.right(90)
t.fd(30)

t.pendown()
t.pencolor('blue')
t.circle(30)
t.penup()
t.left(90)
t.fd(30)
t.pendown()
for i in range(24):
    t.fd(30)
    t.penup()
    t.fd(-30)
    t.left(15)
    t.pendown()
t.penup()
t.pencolor('black')
t.goto(-200,-250)
t.fd(-50)
t.pendown()
t.fillcolor('black')
t.begin_fill()
t.fd(100)
t.left(90)
t.fd(50)
t.left(90)
t.fd(100)
t.left(90)
t.fd(50)
t.end_fill()
t.penup()
t.fd(-50)
t.right(90)
t.fd(50)
t.pendown()
t.fillcolor('black')
t.begin_fill()
t.fd(-200)
t.right(90)
t.fd(50)
t.left(90)
t.fd(200)
t.left(90)
t.fd(50)
t.end_fill()


mainloop()